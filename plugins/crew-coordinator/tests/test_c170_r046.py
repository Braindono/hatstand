"""cc 0.17.0 R-046 transcript wiki: deterministic pages per role, project and decision with backlinks, links and ids
only (no transcript or body text), private files beside the transcripts, archive-not-delete, off switch, regenerated by
the indexer. Run: python3 -B tests/test_c170_r046.py"""
import os as _os, sys as _sys
_sys.path.insert(0, _os.path.dirname(_os.path.abspath(__file__)))
import _env  # noqa: F401  isolate HOME and HARNESS_* first
import json, os, shutil, stat, subprocess, sys, tempfile, unittest
from unittest import mock

HERE = os.path.dirname(os.path.abspath(__file__))
SCRIPTS = os.path.join(HERE, "..", "scripts")
sys.path.insert(0, SCRIPTS)
import harness as H
import transcript_indexer as T
import transcript_wiki as W

MODEL = "claude-opus-5-5"
SID = "11111111-2222-3333-4444-555555555555"


class Wiki(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.mkdtemp()
        self.home = os.path.join(self.tmp, "Exchange")
        os.makedirs(os.path.join(self.home, "_harness"))
        e = mock.patch.dict(os.environ, {"HARNESS_STATE_CACHE": "0"})
        e.start()
        self.addCleanup(e.stop)
        h = H.Harness(self.home)
        h.role_define("operator", "secretary", "secretary")
        self.a = h.register(project="secretary", model=MODEL, session_id=SID)["id"]
        h.role_assign("operator", "secretary", self.a)
        self.d1 = h.record(self.a, "decision", "Mail goes out Mondays", "BODY-SECRET-ONE")["id"]
        self.d2 = h.record(self.a, "decision", "Mail goes out Tuesdays ‮evil|pipe", "Replaces " + self.d1,
                           supersedes=self.d1)["id"]
        self.n = h.record(self.a, "note", "Why Tuesday", "see " + self.d2)["id"]
        h.send(self.a, "operator", "About " + self.d2, subject="Day change")
        self.ledger = os.path.join(self.home, "_harness", "events.jsonl")
        self.vault = os.path.join(self.home, "vault")
        os.makedirs(os.path.join(self.vault, "secretary", "secretary"))
        with open(os.path.join(self.vault, "secretary", "secretary", "2026-10-25-x.md"), "w") as f:
            f.write("meta: {}\n\nVAULT-BODY\n")
        self.root = os.path.join(self.tmp, "Transcripts.noindex")
        os.makedirs(self.root)
        with open(os.path.join(self.root, "2026-10-25-cwd-11111111.md"), "w") as f:
            f.write(f"# Transcript {SID} (cwd)\n\n### operator\n> TRANSCRIPT-SECRET\n")

    def gen(self):
        return W.generate(self.ledger, self.vault, self.root)

    def read(self, rel):
        with open(os.path.join(self.root, "wiki", rel), encoding="utf-8") as f:
            return f.read()

    def all_text(self):
        out = ""
        for dp, _, fs in os.walk(os.path.join(self.root, "wiki")):
            for fn in fs:
                with open(os.path.join(dp, fn), encoding="utf-8") as f:
                    out += f.read()
        return out

    def test_pages_backlinks_and_chain(self):
        r = self.gen()
        self.assertEqual((r["written"], r["archived"]), (r["pages"], 0))
        role, proj, d1, d2 = (self.read("roles/secretary.md"), self.read("projects/secretary.md"),
                              self.read(f"decisions/{self.d1}.md"), self.read(f"decisions/{self.d2}.md"))
        self.assertIn(f"[{self.d2}](../decisions/{self.d2}.md)", role)
        self.assertIn(f"[11111111](../../2026-10-25-cwd-11111111.md)", role)          # link to the transcript, not its text
        self.assertIn("secretary/secretary/2026-10-25-x.md", proj)
        self.assertIn(f"State: superseded (by [{self.d2}]", d1)
        self.assertIn(f"## Supersedes\n\n- [{self.d1}]", d2)
        self.assertIn(f"- {self.n} note · Why Tuesday", d2)                            # cited by
        self.assertIn("Day change", d2)                                                 # thread backlink
        self.assertIn("Linked from: [index](../index.md), [secretary](../roles/secretary.md)", d2)

    def test_links_and_ids_only(self):
        self.gen()
        t = self.all_text()
        for secret in ("BODY-SECRET-ONE", "TRANSCRIPT-SECRET", "VAULT-BODY", "‮"):
            self.assertNotIn(secret, t)
        self.assertIn("Tuesdays evil\\|pipe", t)                                        # bidi dropped, pipe escaped

    def test_deterministic_private_and_archived_not_deleted(self):
        self.gen()
        before = self.all_text()
        r = self.gen()
        self.assertEqual((r["written"], r["same"]), (0, r["pages"]))
        self.assertEqual(self.all_text(), before)
        w = os.path.join(self.root, "wiki")
        self.assertEqual(stat.S_IMODE(os.stat(w).st_mode), 0o700)
        self.assertEqual(stat.S_IMODE(os.stat(os.path.join(w, "index.md")).st_mode), 0o600)
        stale = os.path.join(w, "decisions", "D-00000.md")
        with open(stale, "w") as f:
            f.write("old page\n")
        self.assertEqual(self.gen()["archived"], 1)
        self.assertFalse(os.path.exists(stale))
        kept = [os.path.join(dp, fn) for dp, _, fs in os.walk(os.path.join(w, "_archive")) for fn in fs]
        self.assertEqual([os.path.basename(k) for k in kept], ["D-00000.md"])

    def test_off_switch_and_dry_run(self):
        self.assertEqual(W.generate(self.ledger, self.vault, self.root, dry_run=True)["written"] > 0, True)
        self.assertFalse(os.path.exists(os.path.join(self.root, "wiki")))
        open(os.path.join(self.root, ".wiki-off"), "w").close()
        self.assertTrue(self.gen()["off"])
        self.assertFalse(os.path.exists(os.path.join(self.root, "wiki")))

    def test_old_role_names_map_to_current(self):
        with mock.patch.object(W, "role_aliases", return_value={"corpus-secretary": "secretary"}):
            with open(self.ledger, "a") as f:
                f.write(json.dumps({"seq": 10**6, "type": "role.assigned", "data": {"agent": self.a, "role": "corpus-secretary"}}) + "\n")
            pages = W.pages(W.model(self.ledger, self.vault, self.root), self.vault)
        self.assertIn("roles/secretary.md", pages)
        self.assertNotIn("roles/corpus-secretary.md", pages)

    def test_indexer_regenerates_it_under_isolated_python(self):
        sd = os.path.join(self.tmp, "scripts")
        env = mock.patch.dict(os.environ, {"INDEXER_SCRIPTS": sd, "INDEXER_LAUNCHAGENTS": os.path.join(self.tmp, "LA"),
                                           "INDEXER_LEDGER": self.ledger, "INDEXER_VAULT": self.vault, "INDEXER_ROOT": self.root})
        env.start()
        self.addCleanup(env.stop)

        class R:
            returncode, stderr = 0, ""
        ix = T.Indexer(root=self.root, cache=os.path.join(self.tmp, "cache"), source=os.path.join(self.tmp, "src"), ledger=False)
        T.install(ix, run=lambda cmd: R())
        self.assertTrue(os.path.isfile(os.path.join(sd, "transcript_wiki.py")))
        self.assertTrue(os.path.isfile(os.path.join(sd, "role-aliases.json")))
        p = subprocess.run(["/usr/bin/python3", "-I", "-B", os.path.join(sd, "transcript_indexer.py"), "wiki"],
                           capture_output=True, text=True, timeout=120, env=dict(os.environ))
        self.assertEqual(p.returncode, 0, p.stderr)
        self.assertGreater(json.loads(p.stdout)["pages"], 3)
        self.assertTrue(os.path.isfile(os.path.join(self.root, "wiki", "roles", "secretary.md")))

    def test_wiki_pass_without_the_generator_is_off(self):
        with mock.patch.object(T.os.path, "isfile", return_value=False):
            self.assertTrue(T.wiki_pass(T.Indexer(root=self.root, cache=os.path.join(self.tmp, "c"),
                                                  source=os.path.join(self.tmp, "s"), ledger=False))["off"])


if __name__ == "__main__":
    unittest.main()
