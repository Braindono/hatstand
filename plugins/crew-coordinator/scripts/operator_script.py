#!/usr/bin/env python3
"""0.17.0 (C-onecmd, D-40d27): one-command operator actions. `harness_admin op=operator_script` writes a generated,
idempotent bash script for bulk operator work and returns the single command that runs it. The R-087 launchers are
its first instance (action `launchers`).

Safety:
- Every value in the script comes from a validated item (ids, slugs and refs by pattern; the reason is cleaned and
  shell-quoted). Nothing an agent types reaches the shell unquoted.
- Dry run by default: `bash <script>` prints each command (retag and launchers also run their own read-only dry run);
  `bash <script> apply` runs them.
- Idempotent: each finished step is appended to `<script>.done`; a rerun skips it. The same request makes the same file
  (the name carries a hash of the request), and a file without the generated marker is never overwritten.
- Full paths only: the interpreter, this harness.py and --home are absolute.
Scripts live in <home>/_harness/operator-scripts/ (0700 folder, 0700 files). A `operator_script.written` event records
each one (path, action, items, sha256).
"""
import hashlib
import json
import os
import re
import shlex

MARKER = "# generated by crew-coordinator `harness_admin op=operator_script` (C-onecmd); regenerate, do not edit"
MAX_ITEMS = 200
PY = "/usr/bin/python3"
_AGENT = re.compile(r"^[0-9a-f]{8,64}$")
_SLUG = re.compile(r"^[a-z0-9][a-z0-9-]*$")
_ENTRY = re.compile(r"^[A-Z]-[0-9a-f]{5}$")
_REF = re.compile(r"^(m-[0-9a-f]{12}|D-[0-9a-f]{5})$")
_APPROVAL = re.compile(r"^A-[0-9a-f]{5}$")
ACTIONS = ("retire", "set_project", "retag", "approve", "launchers")


class ScriptError(ValueError):
    pass


def _need(rx, v, what):
    v = str(v if v is not None else "").strip()
    if not rx.match(v):
        raise ScriptError(f"operator_script: {what} {v[:40]!r} is not valid")
    return v


def _reason(v):
    v = " ".join(re.sub(r"[\x00-\x1f\x7f​-‏‪-‮⁦-⁩]", " ", str(v or "")).split())
    return v[:200]


def normalize(action, items, reason=None):
    """-> list of (key, cmd_args, dry_args or None). cmd_args are argv after `harness.py --home H`. Raises ScriptError."""
    if action not in ACTIONS:
        raise ScriptError(f"operator_script: action must be one of {', '.join(ACTIONS)}")
    if action == "launchers":
        if items:
            raise ScriptError("operator_script: launchers takes no items")
        return [("launchers", ["launchers", "--apply"], ["launchers"])]
    if not isinstance(items, list) or not items:
        raise ScriptError("operator_script: items must be a non-empty list")
    if len(items) > MAX_ITEMS:
        raise ScriptError(f"operator_script: at most {MAX_ITEMS} items per script")
    steps, seen = [], set()
    for it in items:
        if action == "retire":
            t = _need(_AGENT, it.get("target") if isinstance(it, dict) else it, "target")
            why = _reason((it.get("reason") if isinstance(it, dict) else None) or reason) or "operator bulk retire"
            key, cmd, dry = f"retire:{t}", ["retire", "--agent", "operator", "--target", t, "--reason", why], None
        elif action == "set_project":
            if not isinstance(it, dict):
                raise ScriptError("operator_script: set_project items are {target, project}")
            t, p = _need(_AGENT, it.get("target"), "target"), _need(_SLUG, it.get("project"), "project")
            key, cmd, dry = f"set_project:{t}:{p}", ["set-project", "--agent", "operator", "--target", t, "--project", p], None
        elif action == "retag":
            if not isinstance(it, dict):
                raise ScriptError("operator_script: retag items are {entry, project, role?, ref?}")
            e, p = _need(_ENTRY, it.get("entry"), "entry"), _need(_SLUG, it.get("project"), "project")
            cmd = ["retag", "--agent", "operator", "--entry", e, "--project", p]
            if it.get("role"):
                cmd += ["--role", _need(_SLUG, it["role"], "role")]
            if it.get("ref"):
                cmd += ["--ref", _need(_REF, it["ref"], "ref")]
            key, dry = f"retag:{e}:{p}:{it.get('role') or ''}", cmd + ["--dry-run"]
        else:   # approve: interactive, the operator types each code
            a = _need(_APPROVAL, it, "approval id")
            key, cmd, dry = f"approve:{a}", ["approve", a], None
        if key in seen:
            continue
        seen.add(key)
        steps.append((key, cmd, dry))
    return steps


def render(action, steps, harness_py, home, requester, path):
    q = shlex.quote
    base = f'"$PY" "$HP" --home "$HX"'
    L = ["#!/bin/bash", MARKER,
         f"# action: {action} · steps: {len(steps)} · requested by: {requester}",
         f"# dry run: bash {q(path)}", f"# apply:   bash {q(path)} apply",
         "set -u", f"PY={q(PY)}", f"HP={q(harness_py)}", f"HX={q(home)}", f"DONE={q(path + '.done')}",
         'MODE="${1:-dry}"',
         'case "$MODE" in dry|apply) ;; *) echo "usage: bash $0 [apply]"; exit 2;; esac',
         'if [ "$MODE" = apply ]; then touch "$DONE"; chmod 600 "$DONE"; fi',
         "ok=0; skip=0; fail=0",
         'done_already() { [ -f "$DONE" ] && grep -qxF "$1" "$DONE"; }',
         'step() { k="$1"; shift; if done_already "$k"; then echo "skip $k (done)"; skip=$((skip+1)); return; fi',
         '  if "$@"; then echo "$k" >> "$DONE"; echo "ok   $k"; ok=$((ok+1)); else echo "FAIL $k"; fail=$((fail+1)); fi; }',
         'show() { k="$1"; shift; if done_already "$k"; then echo "skip $k (done)"; skip=$((skip+1)); else echo "would run: $*"; fi; }',
         'echo "== ' + action + ' ($MODE) =="']
    for key, cmd, dry in steps:
        args = " ".join(q(c) for c in cmd)
        L.append(f'if [ "$MODE" = apply ]; then step {q(key)} {base} {args}; else show {q(key)} {base} {args}'
                 + (f"; {base} {' '.join(q(c) for c in dry)} || true" if dry else "") + "; fi")
    L += ['echo "mode=$MODE ok=$ok skip=$skip fail=$fail"',
          'if [ "$MODE" = dry ]; then echo "nothing changed; to run: bash $0 apply"; fi',
          '[ "$fail" -eq 0 ]']
    return "\n".join(L) + "\n"


def write(home, harness_py, action, items, reason=None, requester="operator"):
    """-> {path, command_dry, command_apply, steps, sha256, reused}. Writes the script; nothing runs."""
    steps = normalize(action, items, reason)
    req = hashlib.sha256(json.dumps([action, [s[0] for s in steps], [s[1] for s in steps]]).encode()).hexdigest()[:10]
    d = os.path.join(home, "_harness", "operator-scripts")
    os.makedirs(d, mode=0o700, exist_ok=True)
    import time
    path = os.path.join(d, f"{time.strftime('%Y-%m-%d')}-{action.replace('_', '-')}-{req}.sh")
    text = render(action, steps, os.path.abspath(harness_py), os.path.abspath(home), requester, path)
    reused = False
    if os.path.lexists(path):
        try:
            with open(path, encoding="utf-8") as f:
                cur = f.read()
        except (OSError, UnicodeDecodeError):
            cur = None
        if os.path.islink(path) or cur is None or MARKER not in cur:
            raise ScriptError(f"operator_script: {path} exists and is not generated; left as is")
        reused = cur == text
    if not reused:
        tmp = path + ".tmp"
        fd = os.open(tmp, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o700)
        with os.fdopen(fd, "w", encoding="utf-8") as f:
            f.write(text)
        os.chmod(tmp, 0o700)
        os.replace(tmp, path)
    sha = hashlib.sha256(text.encode()).hexdigest()
    return {"path": path, "command_dry": f"bash {shlex.quote(path)}", "command_apply": f"bash {shlex.quote(path)} apply",
            "steps": len(steps), "sha256": sha, "reused": reused,
            "do": "give the operator command_dry alone first (D-40d27); command_apply only after the dry run"}
