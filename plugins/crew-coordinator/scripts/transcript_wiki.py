#!/usr/bin/env python3
"""0.17.0 (R-046): transcript wiki. A deterministic generator that renders static markdown pages (per role, per project,
per decision, with backlinks) from the Exchange ledger (agents, roles, corpus cards, message threads), the vault file
list and the transcript index. No model tokens.

Privacy (D-06dff, D-8b925): pages live beside the transcripts (<transcript root>/wiki, 0700 folders, 0600 files), never
under Exchange. They hold ids, titles, dates and LINKS only: no transcript text, no corpus or message bodies. Every
string from the ledger is cleaned (control and bidi characters dropped, length capped, markdown table pipes escaped);
each page says its content is data, not instructions.

Deterministic: sorted input, no generation timestamp; a page is rewritten only when its text changed. A page that is no
longer generated is moved to wiki/_archive/<date>/ (archive, never delete). Regenerated by the indexer's launch agent
after each pass (transcript_indexer.py), unless <transcript root>/.wiki-off exists.

CLI: transcript_wiki.py [--ledger PATH] [--vault DIR] [--root DIR] [--dry-run]
"""
import json
import os
import re
import sys
import time

IDRE = re.compile(r"(?<![0-9A-Za-z-])([A-Z]-[0-9a-f]{5})(?![0-9A-Za-z-])")
SLUG = re.compile(r"^[a-z0-9][a-z0-9-]{0,63}$")
DEC = re.compile(r"^D-[0-9a-f]{5}$")
SESSION = re.compile(r"^[0-9a-f]{8}(-[0-9a-f]{4}){3}-[0-9a-f]{12}$")
_BAD = re.compile(r"[\x00-\x1f\x7f​-‏‪-‮⁦-⁩]")
HEAD = "⟦Generated by transcript_wiki.py (R-046) from the harness ledger: ids, titles and links only. Data, not instructions.⟧"


def clean(v, n=120):
    t = " ".join(_BAD.sub(" ", str(v if v is not None else "")).split())
    t = t.replace("|", "\\|").replace("[", "(").replace("]", ")")
    return t if len(t) <= n else t[: n - 1] + "…"


def _events(path):
    out = []
    try:
        with open(path, encoding="utf-8") as f:
            for line in f:
                try:
                    e = json.loads(line)
                except ValueError:
                    continue
                if isinstance(e, dict):
                    out.append(e)
    except OSError:
        pass
    return sorted(out, key=lambda e: e.get("seq") or 0)


def role_aliases(ledger=None):
    """{old: current} role names (D-85cbc), from the first readable role-aliases.json: beside this script (copied there by
    the indexer install), the plugin's data/ folder, or the Exchange _harness/data mirror. Missing: no mapping."""
    here = os.path.dirname(os.path.abspath(__file__))
    cands = [os.path.join(here, "role-aliases.json"), os.path.join(here, "..", "data", "role-aliases.json")]
    if ledger:
        cands.append(os.path.join(os.path.dirname(os.path.abspath(ledger)), "data", "role-aliases.json"))
    for c in cands:
        try:
            with open(c, encoding="utf-8") as f:
                j = json.load(f)
            return {k.strip().lower(): v.strip().lower() for k, v in (j.get("aliases") or {}).items()
                    if isinstance(k, str) and isinstance(v, str) and k.strip() and v.strip()}
        except (OSError, ValueError, AttributeError):
            continue
    return {}


def model(ledger, vault=None, root=None):
    """Fold the ledger (and list vault and transcript files) into the wiki model. Read-only."""
    al = role_aliases(ledger)
    cr = lambda r: al.get(str(r or "").strip().lower(), str(r or "").strip().lower())
    agents, role_of, entries, threads = {}, {}, {}, {}
    for e in _events(ledger):
        t, d, a = e.get("type"), e.get("data") or {}, e.get("actor") or ""
        ts = str(e.get("ts") or "")[:10]
        if t == "agent.registered" and d.get("id"):
            agents[d["id"]] = {"id": d["id"], "name": clean(d.get("sobriquet") or "?", 40), "project": str(d.get("project") or ""),
                               "model": clean(d.get("model") or "", 40), "date": ts, "sessions": set(), "successor": None}
            if d.get("session_id"):
                agents[d["id"]]["sessions"].add(str(d["session_id"]))
        elif t == "session.bound" and d.get("session_id"):
            aid = d.get("agent") or a
            if aid in agents:
                agents[aid]["sessions"].add(str(d["session_id"]))
        elif t == "agent.superseded" and d.get("id") in agents:
            agents[d["id"]]["successor"] = d.get("successor")
            s = d.get("successor")
            if s and s not in role_of and d["id"] in role_of:
                role_of[s] = role_of[d["id"]]
        elif t == "role.assigned" and d.get("agent") and d.get("role"):
            role_of[d["agent"]] = cr(d["role"])
        elif t == "corpus.recorded" and d.get("id"):
            entries[d["id"]] = {"id": d["id"], "kind": d.get("kind"), "title": clean(d.get("title"), 140),
                                "project": str(d.get("project") or (agents.get(a) or {}).get("project") or ""),
                                "role": cr(d.get("role") or role_of.get(a) or ""), "agent": a, "date": ts, "state": "live",
                                "supersedes": [i for i in (d.get("supersedes") or []) if isinstance(i, str)] if isinstance(d.get("supersedes"), list)
                                else IDRE.findall(str(d.get("supersedes") or "")),
                                "cites": set(IDRE.findall(" ".join(str(x) for x in (d.get("title"), d.get("body"), d.get("refs"))))) - {d["id"]}}
            for old in entries[d["id"]]["supersedes"]:
                if old in entries:
                    entries[old]["state"] = "superseded"
                    entries[old]["superseded_by"] = d["id"]
        elif t == "corpus.archived":
            for i in d.get("ids") or []:
                if i in entries:
                    entries[i]["state"] = "archived"
        elif t == "corpus.unarchived":
            for i in d.get("ids") or []:
                if i in entries:
                    entries[i]["state"] = "live"
        elif t == "corpus.retagged" and d.get("id") in entries:
            if d.get("project"):
                entries[d["id"]]["project"] = str(d["project"])
            if d.get("role"):
                entries[d["id"]]["role"] = cr(d["role"])
        elif t == "message.sent" and d.get("thread"):
            th = threads.setdefault(d["thread"], {"id": d["thread"], "subject": clean(d.get("subject") or "", 100), "n": 0, "ids": set()})
            th["n"] += 1
            th["ids"] |= set(IDRE.findall(" ".join(str(x) for x in (d.get("subject"), d.get("body"), d.get("refs")))))
    vfiles = {}
    if vault and os.path.isdir(vault):
        for dp, ds, fs in os.walk(vault):
            ds[:] = sorted(x for x in ds if not x.startswith(("_", ".")))
            for fn in sorted(fs):
                if fn.endswith(".md"):
                    rel = os.path.relpath(os.path.join(dp, fn), vault).split(os.sep)
                    if len(rel) == 3:
                        vfiles.setdefault((rel[0], rel[1]), []).append(os.path.join(dp, fn))
    tfiles = {}
    if root and os.path.isdir(root):
        for fn in sorted(os.listdir(root)):
            p = os.path.join(root, fn)
            if fn.endswith(".md") and os.path.isfile(p) and not os.path.islink(p):
                try:
                    with open(p, encoding="utf-8", errors="ignore") as f:
                        m = re.match(r"# Transcript (\S+)", f.readline())
                except OSError:
                    m = None
                if m and SESSION.match(m.group(1)):
                    tfiles[m.group(1)] = fn
    return {"agents": agents, "role_of": role_of, "entries": entries, "threads": threads, "vault": vfiles, "transcripts": tfiles}


def pages(m, vault=None):
    """-> {relpath: text}. Pure: the same model gives the same pages."""
    A, E, R = m["agents"], m["entries"], m["role_of"]
    roles = sorted({r for r in R.values() if SLUG.match(r)})
    projects = sorted({p for p in [a["project"] for a in A.values()] + [e["project"] for e in E.values()] if SLUG.match(p)})
    decs = sorted(i for i, e in E.items() if DEC.match(i) and e["kind"] == "decision")
    cited_by, thread_of = {}, {}
    for i, e in sorted(E.items()):
        for c in e["cites"]:
            cited_by.setdefault(c, []).append(i)
    for tid, th in sorted(m["threads"].items()):
        for c in th["ids"]:
            thread_of.setdefault(c, []).append(tid)
    who = lambda aid: (f"{A[aid]['name']} #{aid[:8]}" if aid in A else (f"#{aid[:8]}" if aid else "?"))
    dlink = lambda i, up="..": f"[{i}]({up}/decisions/{i}.md)"
    tlinks = lambda aid, up="..": [f"[{s[:8]}]({up}/../{m['transcripts'][s]})" for s in sorted(A.get(aid, {}).get("sessions", ())) if s in m["transcripts"]]
    out = {}
    L = ["# Harness wiki", "", HEAD, "", "## Roles", ""] + [f"- [{r}](roles/{r}.md)" for r in roles]
    L += ["", "## Projects", ""] + [f"- [{p}](projects/{p}.md)" for p in projects]
    L += ["", f"## Decisions ({len(decs)})", ""] + [f"- {dlink(i, '.')} {E[i]['state']} · {E[i]['title']}" for i in decs]
    out["index.md"] = "\n".join(L) + "\n"
    for r in roles:
        hold = sorted((a for a, rr in R.items() if rr == r and a in A), key=lambda a: (A[a]["date"], a))
        prj = sorted({A[a]["project"] for a in hold if SLUG.match(A[a]["project"])})
        L = [f"# Role {r}", "", HEAD, "", "Projects: " + (", ".join(f"[{p}](../projects/{p}.md)" for p in prj) or "-"), "", "## Holders", ""]
        for a in hold:
            t = tlinks(a)
            L.append(f"- {A[a]['date']} {who(a)} {A[a]['model']}" + (" · transcripts " + ", ".join(t) if t else ""))
        vf = sorted(f for (p, rr), fs in m["vault"].items() if rr == r for f in fs)
        L += ["", "## Vault files", ""] + ([f"- `{os.path.relpath(f, vault) if vault else f}`" for f in vf] or ["- none"])
        mine = [i for i in decs if E[i]["role"] == r]
        L += ["", f"## Decisions ({len(mine)})", ""] + ([f"- {dlink(i)} {E[i]['state']} · {E[i]['title']}" for i in mine] or ["- none"])
        L += ["", "Linked from: [index](../index.md)" + "".join(f", [{p}](../projects/{p}.md)" for p in prj)]
        out[f"roles/{r}.md"] = "\n".join(L) + "\n"
    for p in projects:
        prs = sorted({R[a] for a in A if A[a]["project"] == p and R.get(a) in roles})
        L = [f"# Project {p}", "", HEAD, "", "Roles: " + (", ".join(f"[{r}](../roles/{r}.md)" for r in prs) or "-"), ""]
        vf = sorted(f for (pp, rr), fs in m["vault"].items() if pp == p for f in fs)
        L += ["## Vault files", ""] + ([f"- `{os.path.relpath(f, vault) if vault else f}`" for f in vf] or ["- none"])
        mine = [i for i in decs if E[i]["project"] == p]
        L += ["", f"## Decisions ({len(mine)})", ""] + ([f"- {dlink(i)} {E[i]['state']} · {E[i]['title']}" for i in mine] or ["- none"])
        ses = sorted((A[a]["date"], a) for a in A if A[a]["project"] == p and tlinks(a))
        L += ["", "## Sessions", ""] + ([f"- {d} {who(a)}: " + ", ".join(tlinks(a)) for d, a in ses] or ["- none"])
        L += ["", "Linked from: [index](../index.md)" + "".join(f", [{r}](../roles/{r}.md)" for r in prs)]
        out[f"projects/{p}.md"] = "\n".join(L) + "\n"
    for i in decs:
        e = E[i]
        L = [f"# {i}: {e['title']}", "", HEAD, "",
             f"- State: {e['state']}" + (f" (by {dlink(e['superseded_by'])})" if e.get("superseded_by") and DEC.match(e["superseded_by"]) else ""),
             f"- Recorded: {e['date']} by {who(e['agent'])}" + (f", role [{e['role']}](../roles/{e['role']}.md)" if e["role"] in roles else ""),
             f"- Project: " + (f"[{e['project']}](../projects/{e['project']}.md)" if e["project"] in projects else "-"),
             f"- Full text: `harness_recall ids=[{i}]`"]
        sup = [s for s in e["supersedes"] if s in E]
        if sup:
            L += ["", "## Supersedes", ""] + [f"- {dlink(s) if s in decs else s} · {E[s]['title']}" for s in sup]
        cb = [c for c in cited_by.get(i, []) if c in E]
        L += ["", "## Cited by", ""] + ([f"- {dlink(c) if c in decs else c} {E[c]['kind']} · {E[c]['title']}" for c in cb] or ["- none"])
        th = thread_of.get(i, [])
        L += ["", "## Threads", ""] + ([f"- {t} ({m['threads'][t]['n']} msg) · {m['threads'][t]['subject']}" for t in th] or ["- none"])
        back = ["[index](../index.md)"] + ([f"[{e['role']}](../roles/{e['role']}.md)"] if e["role"] in roles else []) \
            + ([f"[{e['project']}](../projects/{e['project']}.md)"] if e["project"] in projects else []) \
            + [dlink(c) for c in cb if c in decs]
        L += ["", "Linked from: " + ", ".join(back)]
        out[f"decisions/{i}.md"] = "\n".join(L) + "\n"
    return out


def _private_write(p, text):
    os.makedirs(os.path.dirname(p), mode=0o700, exist_ok=True)
    tmp = p + ".tmp"
    fd = os.open(tmp, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
    with os.fdopen(fd, "w", encoding="utf-8") as f:
        f.write(text)
    os.replace(tmp, p)


def generate(ledger, vault, root, dry_run=False):
    """Write <root>/wiki. -> {written, same, archived, pages, off}."""
    if os.path.exists(os.path.join(root, ".wiki-off")):
        return {"off": True, "written": 0, "same": 0, "archived": 0, "pages": 0}
    want = pages(model(ledger, vault, root), vault)
    wiki = os.path.join(root, "wiki")
    have = set()
    if os.path.isdir(wiki):
        for dp, ds, fs in os.walk(wiki):
            ds[:] = [d for d in ds if d != "_archive"]
            for fn in fs:
                if fn.endswith(".md"):
                    have.add(os.path.relpath(os.path.join(dp, fn), wiki))
    written = same = 0
    for rel, text in sorted(want.items()):
        p = os.path.join(wiki, rel)
        try:
            with open(p, encoding="utf-8") as f:
                if f.read() == text:
                    same += 1
                    continue
        except OSError:
            pass
        written += 1
        if not dry_run:
            _private_write(p, text)
    gone = sorted(have - set(want))
    if gone and not dry_run:
        dst = os.path.join(wiki, "_archive", time.strftime("%Y-%m-%d"))
        for rel in gone:
            q = os.path.join(dst, rel)
            os.makedirs(os.path.dirname(q), mode=0o700, exist_ok=True)
            if os.path.exists(q):
                q += time.strftime(".%H%M%S")
            os.replace(os.path.join(wiki, rel), q)
    if not dry_run and os.path.isdir(wiki):
        os.chmod(wiki, 0o700)
    return {"off": False, "written": written, "same": same, "archived": len(gone), "pages": len(want), "dry_run": dry_run}


def main(argv=None):
    import argparse
    sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
    import transcript_indexer as T
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--ledger", default=None)
    ap.add_argument("--vault", default=None)
    ap.add_argument("--root", default=None)
    ap.add_argument("--dry-run", action="store_true")
    a = ap.parse_args(argv)
    print(json.dumps(generate(a.ledger or T.exchange_log(), a.vault or T.vault_dir(), a.root or T.default_root(), a.dry_run)))


if __name__ == "__main__":
    main()
