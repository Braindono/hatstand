#!/usr/bin/env python3
"""0.17.0 (R-087, operator idea fzj12n): thin launchers for operator-invokable entry points in ~/Claude/scripts.

Each launcher is one `exec <interpreter> "<real path>" "$@"` line, so the real scripts stay where they are (moving them
breaks hooks, mirrors and 70+ hard-coded paths). Generated files carry a marker line; a file without it is never
overwritten. A README.md index lists every launcher and its target.

Targets come from the defaults below or from the operator's private ~/.config/crew-coordinator/operator.json key
`operator_launchers` ({name: path}), NEVER from the shared config.json: any agent can edit that file, and a launcher is
code the operator runs. Every target must resolve under ~/Claude/Projects or ~/Claude/Code. Missing targets are skipped
and reported. Dry run by default; `--apply` writes.
"""
import os
import stat

MARKER = "# generated by crew-coordinator `harness.py launchers` (R-087); edit the real script, not this file"
ROOTS = ("~/Claude/Projects", "~/Claude/Code")
# name -> (path with $EXCHANGE / $OPS / $PROJECTS, purpose)
DEFAULTS = {
    "harness": ("$EXCHANGE/_harness/bin/harness.py", "Harness CLI: approve <id>, pending, deny, health, recall, ..."),
    "wake": ("$EXCHANGE/_harness/wake.py", "doorbell / wake helper"),
    "health": ("$EXCHANGE/_harness/bin/health.py", "corpus health report (read-only)"),
    "dashboard": ("$EXCHANGE/_harness/bin/dashboard_server.py", "local dashboard server"),
    "run-jobs": ("$OPS/projects/orchestration/scripts/run_jobs.py", "deterministic scheduled jobs (steward pass, evals)"),
    "bootstrap": ("$OPS/projects/orchestration/scripts/bootstrap.sh", "orchestration bootstrap"),
    "capture": ("$EXCHANGE/projects/design-system/build/capture/capture.mjs", "design-system screenshot capture (node)"),
    "regen-tokens": ("$PROJECTS/Design_System/project/scripts/regen_tokens.py", "regenerate design tokens"),
    "build-outputs": ("$PROJECTS/Secretary/bin/build_outputs.py", "secretary: build Outputs"),
}
INTERP = {".py": "/usr/bin/python3", ".sh": "/bin/bash", ".mjs": "/usr/bin/env node", ".js": "/usr/bin/env node"}


def _under(p, root):
    p, root = os.path.realpath(p), os.path.realpath(os.path.expanduser(root))
    return p == root or p.startswith(root + os.sep)


def targets(home, operator_cfg=None):
    """-> [{name, target, purpose, ok, why?}] (sorted by name)."""
    ops = os.environ.get("HARNESS_OPS_ROOT") or os.path.expanduser("~/Claude/Code/harness-ops")
    subst = {"$EXCHANGE": home, "$OPS": ops, "$PROJECTS": os.path.expanduser("~/Claude/Projects")}
    spec = {k: v for k, v in DEFAULTS.items()}
    extra = (operator_cfg or {}).get("operator_launchers")
    if isinstance(extra, dict):
        for k, v in extra.items():
            if isinstance(k, str) and isinstance(v, str) and k.replace("-", "").isalnum():
                spec[k] = (v, "operator.json entry")
    out = []
    for name, (raw, purpose) in sorted(spec.items()):
        t = raw
        for k, v in subst.items():
            t = t.replace(k, v)
        t = os.path.abspath(os.path.expanduser(t))
        row = {"name": name, "target": t, "purpose": purpose, "ok": True}
        ext = os.path.splitext(t)[1]
        if ext not in INTERP:
            row.update(ok=False, why="unsupported file type %r" % ext)
        elif not any(_under(t, r) for r in ROOTS):
            row.update(ok=False, why="outside ~/Claude/Projects and ~/Claude/Code")
        elif not os.path.isfile(t):
            row.update(ok=False, why="target missing")
        out.append(row)
    return out


def launcher_text(target):
    return "#!/bin/sh\n%s\nexec %s \"%s\" \"$@\"\n" % (MARKER, INTERP[os.path.splitext(target)[1]], target.replace('"', '\\"'))


def readme_text(rows):
    L = ["# ~/Claude/scripts", "", MARKER.replace("# ", "", 1) + ".", "",
         "Thin launchers: each runs the real script in place with your arguments. Originals stay where they are.", "",
         "| Command | Runs | Purpose |", "|---|---|---|"]
    L += ["| `%s` | `%s` | %s |" % (r["name"], r["target"], r["purpose"]) for r in rows if r["ok"]]
    skipped = [r for r in rows if not r["ok"]]
    if skipped:
        L += ["", "Not generated:"] + ["- `%s`: %s (%s)" % (r["name"], r["why"], r["target"]) for r in skipped]
    return "\n".join(L) + "\n"


def plan(home, dest, operator_cfg=None):
    """-> {"dir", "write": [...], "same": [...], "conflict": [...], "skipped": [...], "rows"}. Writes nothing."""
    rows = targets(home, operator_cfg)
    res = {"dir": dest, "write": [], "same": [], "conflict": [], "skipped": [], "rows": rows}
    files = {r["name"]: launcher_text(r["target"]) for r in rows if r["ok"]}
    files["README.md"] = readme_text(rows)
    for r in rows:
        if not r["ok"]:
            res["skipped"].append("%s: %s" % (r["name"], r["why"]))
    for fn, text in sorted(files.items()):
        p = os.path.join(dest, fn)
        if os.path.lexists(p):
            try:
                with open(p, "r", encoding="utf-8") as f:
                    cur = f.read()
            except (OSError, UnicodeDecodeError):
                cur = None
            if cur == text:
                res["same"].append(fn)
                continue
            if os.path.islink(p) or cur is None or MARKER not in cur:
                res["conflict"].append(fn)       # not ours: never overwritten
                continue
        res["write"].append(fn)
    res["_files"] = files
    return res


def apply(res):
    """Write the planned files (0755 launchers, 0644 README) into res["dir"] (made 0700 if new)."""
    dest = res["dir"]
    if not os.path.isdir(dest):
        os.makedirs(dest, mode=0o700)
    done = []
    for fn in res["write"]:
        p = os.path.join(dest, fn)
        tmp = p + ".tmp"
        with open(tmp, "w", encoding="utf-8") as f:
            f.write(res["_files"][fn])
        os.chmod(tmp, 0o644 if fn == "README.md" else 0o755)
        os.replace(tmp, p)
        done.append(fn)
    return done


def summary(res, applied=None):
    out = {k: res[k] for k in ("dir", "write", "same", "conflict", "skipped")}
    if applied is not None:
        out["written"] = applied
    else:
        out["dry_run"] = True
        out["next"] = "re-run with --apply to write %d file(s)" % len(res["write"])
    return out


def mode_ok(path):
    return bool(os.stat(path).st_mode & stat.S_IXUSR)
